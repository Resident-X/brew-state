#!/usr/bin/env python3
"""Writes E_zc_delay.cir: the zero-crossing detector (R630 R631 U602 R632 C630) at every end of
every stated spread, one transient per combination, measuring where the output crosses the
controller's input thresholds.  Run: python3 -I E_zc_delay_gen.py   then   ngspice -b E_zc_delay.cir -o E_zc_delay.log

Inputs and where each was read
  supply            216 V and 253 V rms, 50 Hz                    constraints record, Supply (60 Hz appears there only as the adopter's alternate)
  R630 R631         60.4 kohm 1 %, 100 ppm/K, air 70 degC          Fosan FRC series sheet FJ-JS-3001-V3.0 p.4-5; constraints record, Enclosure air temperature
                    ends: 60.4k x 0.99 x (1 - 100e-6 x 45) = 59.5 k ; 60.4k x 1.01 x (1 + 100e-6 x 45) = 61.3 k
  LED forward drop  1.4 V maximum at 20 mA (Lite-On LTV-814 BNS-OD-C131/A4 p.9, VF); 1.2 V typical at 20 mA is the only lower figure the sheet has
  CTR               minimum 20 % and maximum 300 % at IF = 1 mA, VCE = 5 V (same table).  No figure is stated at any other IF.
  threshold model   DOCUMENTED ASSUMPTION, not a sheet figure: CTR is taken as constant over IF, so the collector current is CTR x |IF|; the sheet gives it only at
                    1 mA.  The two CTR ends bracket the model; neither is a guaranteed value at the smaller currents the edges occur at.
  saturation knee   VCE(sat) max 0.2 V at IF = 20 mA, IC = 1 mA (same table): the collector current is scaled by tanh(VCE / 0.2 V)
  response lag      18 us maximum rise and fall at RL = 100 ohm, VCE = 2 V, IC = 2 mA (same table); nothing is stated at this load: modelled as a lag of 18 us / 2.2
  controller input  VIL max 0.3 VDD, VIH min 0.7 VDD (STM32H743 DS12110 Rev 10 Table 60); VDD 3.0 V and 3.6 V ends (the 3.3 V rail's span is the controller sheet's)
  R632              22 kohm 1 %; C630 1 nF 10 % X7R
"""
import itertools, math

VPK = {"216": 216 * math.sqrt(2), "253": 253 * math.sqrt(2)}
R_END = {"lo": 59.53e3, "hi": 61.28e3}              # R630 = R631
CTR = {"min": 0.2, "max": 3.0}
VF_IS = {"vf1.4": 3.5e-14, "vf1.2": 1.6e-12}        # n = 2: VF = 1.4 V and 1.2 V at 20 mA
VDD = {"3.0": 3.0, "3.6": 3.6}

head = """Zero-crossing detector: R630 R631 U602 R632 C630, every end of the stated spreads, output edges against the controller's thresholds
* Generated by E_zc_delay_gen.py; inputs and sources are listed there.  Refs and values are the sheet "Zero-crossing detector"'s.
* U602 is modelled: two antiparallel diodes (the LED) and a collector current source CTR x |IF| with a saturation knee and a response lag.
* Vsns is a 0 V current probe; Vctr holds CTR; Vsup is the +3V3 rail; Vgnd ties NEUTRAL to the simulator's ground (GND is ground by name);
* Vamp sets the supply's peak and Bline is the supply: V = Vamp x sin(2 pi 50 t), zero crossings at t = 0, 10 ms, 20 ms ...
R630 LINE ZC_N1 60.4k
R631 ZC_N1 ZC_LED_A 60.4k
Vsns ZC_LED_A ZC_LEDM 0
D1 ZC_LEDM NEUTRAL DLED
D2 NEUTRAL ZC_LEDM DLED
.model DLED D(IS=3.5e-14 N=2)
Bq ZC_IC 0 I=v(CTRN)*abs(i(Vsns))
Rlag ZC_IC ZC_ICL 1k
Clag ZC_ICL 0 8.2n
Gq ZC_IN GND VALUE={v(CTRN)*abs(i(Vsns))*tanh(v(ZC_IN)/0.2)}
R632 ZC_IN +3V3 22k
C630 ZC_IN GND 1n
Vctr CTRN 0 0.2
Vsup +3V3 0 3.3
Vgnd NEUTRAL 0 0
Vamp AMPN 0 357.8
Bline LINE NEUTRAL V=v(AMPN)*sin(2*3.14159265*50*time)
.tran 5u 60m
.control
"""
# The Bq/Rlag/Clag chain above is replaced by a lag applied to the controlling current below; keep the deck simple:
head = head.replace("Bq ZC_IC 0 I=v(CTRN)*abs(i(Vsns))\nRlag ZC_IC ZC_ICL 1k\nClag ZC_ICL 0 8.2n\n", "")
# response lag: the LED current seen by the transistor is passed through a first-order lag of 8.2 us (18 us / 2.2)
head = head.replace("Gq ZC_IN GND VALUE={v(CTRN)*abs(i(Vsns))*tanh(v(ZC_IN)/0.2)}",
                    "Bif ZC_IF 0 V=abs(i(Vsns))*1k\nRlag ZC_IF ZC_IFL 1k\nClag ZC_IFL 0 8.2n\nGq ZC_IN GND VALUE={v(CTRN)*v(ZC_IFL)/1k*tanh(v(ZC_IN)/0.2)}")

lines = [head.rstrip("\n")]
meas_names = []
idx = 0
for (vk, vp), (rk, rv), (ck, cv), (fk, fi), (dk, dv) in itertools.product(
        VPK.items(), R_END.items(), CTR.items(), VF_IS.items(), VDD.items()):
    idx += 1
    tag = f"v{vk}_r{rk}_ctr{ck}_{fk}_vdd{dk}"
    vil, vih = 0.3 * dv, 0.7 * dv
    lines.append(f"alter Vamp = {vp:.3f}")
    lines.append(f"alter R630 = {rv:.1f}")
    lines.append(f"alter R631 = {rv:.1f}")
    lines.append(f"alter Vctr = {cv}")
    lines.append(f"altermod D1 is = {fi}")
    lines.append(f"altermod D2 is = {fi}")
    lines.append(f"alter Vsup = {dv}")
    lines.append("run")
    lines.append(f"meas tran tf_{idx} WHEN v(ZC_IN)={vil:.3f} FALL=3")
    lines.append(f"meas tran tr_{idx} WHEN v(ZC_IN)={vih:.3f} RISE=3")
    meas_names.append((idx, tag))
lines.append(".endc")
lines.append(".end")
open("E_zc_delay.cir", "w").write("\n".join(lines) + "\n")
open("E_zc_delay.map", "w").write("\n".join(f"{i} {t}" for i, t in meas_names) + "\n")
print("wrote E_zc_delay.cir with", idx, "runs")
